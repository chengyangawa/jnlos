#!/usr/bin/env bash
# ============================================================
# sync-to-wsl.sh - 源码同步到 WSL 工作目录脚本
#
# 功能：
#   将 Windows 侧工程源码同步到 WSL 中的工作目录，
#   便于在 WSL 中执行 archiso 构建。
#
# 用法：
#   bash sync-to-wsl.sh [源目录] [目标目录]
#
# 参数：
#   源目录   - 默认：当前工程的 src/ 目录
#   目标目录 - 默认：~/jnl-os-build/
# ============================================================
set -euo pipefail

# 颜色定义（用于终端彩色输出）
COLOR_GREEN='\033[0;32m'
COLOR_RED='\033[0;31m'
COLOR_YELLOW='\033[0;33m'
COLOR_RESET='\033[0m'

# ------------------------------------------------------------
# 解析参数
# ------------------------------------------------------------
# 获取脚本所在目录，用于推导默认源目录
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 默认源目录：工程根目录下的 src/
DEFAULT_SRC="${SCRIPT_DIR}/../src"
# 默认目标目录：WSL 用户主目录下的工作目录
DEFAULT_DST="${HOME}/jnl-os-build/"

# 源目录：取第一个参数或默认值
SRC_DIR="${1:-${DEFAULT_SRC}}"
# 目标目录：取第二个参数或默认值
DST_DIR="${2:-${DEFAULT_DST}}"

# ------------------------------------------------------------
# 校验源目录是否存在
# ------------------------------------------------------------
echo -e "${COLOR_YELLOW}[同步] 校验源目录...${COLOR_RESET}"

# 转换为绝对路径
SRC_DIR="$(cd "${SRC_DIR}" && pwd)"

if [[ ! -d "${SRC_DIR}" ]]; then
    echo -e "${COLOR_RED}错误：源目录不存在：${SRC_DIR}${COLOR_RESET}"
    exit 1
fi

echo -e "${COLOR_GREEN}源目录：${SRC_DIR}${COLOR_RESET}"
echo -e "${COLOR_GREEN}目标目录：${DST_DIR}${COLOR_RESET}"

# ------------------------------------------------------------
# 创建目标目录
# ------------------------------------------------------------
mkdir -p "${DST_DIR}"

# ------------------------------------------------------------
# 使用 rsync 同步源码
# 参数说明：
#   -a       归档模式（保留权限、时间戳、符号链接等）
#   -v       详细输出
#   --delete 删除目标中源端已不存在的文件（保持镜像一致）
#   --exclude 排除 __pycache__ 目录
#   --exclude 排除 *.pyc 文件
# ------------------------------------------------------------
echo -e "${COLOR_YELLOW}[同步] 开始 rsync 同步...${COLOR_RESET}"

rsync -av --delete \
    --exclude '__pycache__' \
    --exclude '*.pyc' \
    "${SRC_DIR}/" "${DST_DIR}/src/"

# ------------------------------------------------------------
# 统计并输出同步的文件数量
# ------------------------------------------------------------
FILE_COUNT=$(find "${DST_DIR}/src/" -type f | wc -l)
echo -e "${COLOR_GREEN}[同步] 同步完成，共 ${FILE_COUNT} 个文件。${COLOR_RESET}"
